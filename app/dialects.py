# LCSystemF1（STM32F103C8 三轴控制板，串口）
# ══════════════════════════════════════════════════════════


class F1Dialect:
    """LCSystemF1 串口板。

    指令集只有 G00 / G01 / G02 / G28 / M50：
      - **没有 IO 输出指令**（不能控制气阀）
      - **没有 G4 驻留**（延时无法在板内实现）
      - **没有 G92**（无法软件清零）
      - 没有 M400（一问一答本身就保证了同步）

    所以这个方言的输出**只有纯运动**。所有 IO 事件、驻留、模态设置
    都会被丢掉——如果将来板子加了 IO 能力，再补上。

    实测特性（见 docs/F1板卡测试报告.md）：
      - 无加减速，耗时精确等于「距离 ÷ 速度」
      - 短线段无额外开销，可自由切段
      - G02 精度完美但慢 2.7 倍 → 不用圆弧
    """

    name = "f1"
    queued_io = True   # 一问一答，天然同步；不需要 M400
    max_line_len = 89  # 正文上限（整帧 95 不含 CR）
    from .model import DIALECTS as _D
    caps = _D["f1"]

    def __init__(self, rapid_feed: float = 3000.0):
        # G00 在 F1 上是固定 3000mm/min，无法通过 F 改
        self.rapid_feed = rapid_feed

    def header(self, ctx: Ctx) -> list[str]:
        return ["; F1 dialect - motion only (no IO / no dwell)"]

    def ensure_closed(self, ctx: Ctx, io: int, level: int) -> list[str]:
        # F1 没有 IO 输出，这条被丢弃
        return []

    def travel(self, ctx: Ctx, x: float, y: float, feed: float) -> list[str]:
        # G00 在 F1 上是固定速度，带 F 会被忽略但不报错
        return [f"G00 X{_f(x)} Y{_f(y)}"]

    def print_move(self, ctx: Ctx, x: float, y: float, feed: float) -> list[str]:
        return [f"G01 X{_f(x)} Y{_f(y)} F{int(feed)}"]

    def move_z(self, ctx: Ctx, z: float, feed: float) -> list[str]:
        return [f"G00 Z{_f(z)}"]

    def valve(self, ctx: Ctx, ev: IOEvent) -> list[str]:
        # F1 不支持 IO 控制，静默丢弃
        return []

    def dwell(self, ctx: Ctx, ms: int) -> list[str]:
        # F1 没有 G4，延时无法实现
        return []

    def wait_motion(self, ctx: Ctx) -> list[str]:
        # 一问一答，不需要
        return []

    def footer(self, ctx: Ctx) -> list[str]:
        return ["; end"]

    def arc(self, ctx: Ctx, x: float, y: float, i: float, j: float, feed: float) -> list[str]:
        """圆弧（暂不用于生成，保留接口）。

        实测比直线离散慢 2.7 倍，不建议用。
        """
        return [f"G02 X{_f(x)} Y{_f(y)} I{_f(i)} J{_f(j)} F{int(feed)}"]
