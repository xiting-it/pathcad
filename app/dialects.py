"""方言抽象 + 三套实现。

核心是 caps.queued_io：
  True  → IO 随运动排队（Klipper），直接输出，时序精确
  False → IO 由解析器执行（Marlin/待测自研板），必须插 M400 强制停车

这一个字段把「多套方案」压缩成配置。
"""

from __future__ import annotations

from .version import APP_NAME, VERSION

from dataclasses import dataclass
from typing import Protocol

from .model import IOEvent, Machine, Process


@dataclass
class Ctx:
    """输出一行时的上下文。"""

    machine: Machine
    process: Process
    z: float = 0.0


class Dialect(Protocol):
    name: str
    queued_io: bool
    max_line_len: int

    def header(self, ctx: Ctx) -> list[str]: ...
    def ensure_closed(self, ctx: Ctx, io: int, level: int) -> list[str]: ...
    def travel(self, ctx: Ctx, x: float, y: float, feed: float) -> list[str]: ...
    def move_z(self, ctx: Ctx, z: float, feed: float) -> list[str]: ...
    def valve(self, ctx: Ctx, ev: IOEvent) -> list[str]: ...
    def dwell(self, ctx: Ctx, ms: int) -> list[str]: ...
    def wait_motion(self, ctx: Ctx) -> list[str]: ...
    def footer(self, ctx: Ctx) -> list[str]: ...
    def print_move(self, ctx: Ctx, x: float, y: float, feed: float) -> list[str]: ...


def _f(v: float, nd: int = 3) -> str:
    s = f"{v:.{nd}f}"
    return s.rstrip("0").rstrip(".") if "." in s else s


# ════════════════════════════════════════════════════════
# IR → 文本
# ════════════════════════════════════════════════════════


def render_instr(d, ins, ctx: Ctx) -> list[str]:
    """把一条 IR 指令翻译成目标方言的文本行。

    这是 P3 的分界线：编译器只说「移动到 (x,y)」「打开工具 T1」，
    至于写成 G0/G1/M121/M3/SET_PIN，由方言在这里决定。

    加一种新硬件 = 实现这个分派 + 那几个 emit 方法，不用碰几何和工艺。
    """
    kind = ins.kind

    if kind == "comment":
        return [ins.text] if ins.text else [""]

    if kind == "modal":
        return [ins.text] if ins.text else []

    if kind == "move":
        if ins.x is None and ins.y is None and ins.z is not None:
            return d.move_z(ctx, ins.z, ins.feed or 0.0)
        x = ins.x if ins.x is not None else 0.0
        y = ins.y if ins.y is not None else 0.0
        feed = ins.feed or 0.0
        if ins.rapid:
            return d.travel(ctx, x, y, feed)
        return d.print_move(ctx, x, y, feed)

    if kind in ("tool_on", "tool_off"):
        ev = IOEvent(io=int(ins.channel or 0), level=int(ins.level or 0), delay_ms=0)
        return d.valve(ctx, ev)

    if kind == "dwell":
        return d.dwell(ctx, ins.ms)

    if kind == "wait":
        return d.wait_motion(ctx)

    if kind == "end":
        return d.footer(ctx)

    return []


# ══════════════════════════════════════════════════════════
# LCSystem（自研板，UDP）
# ══════════════════════════════════════════════════════════


class LCDialect:
    """自研 i.MX RT1170 网口板。

    - 阀：M121 U<n> V0/1（实测可用，IOOUT 会变化）
    - **不支持 G4 延时**：发了会让队列卡死回 E020 且不自恢复，
      所以 dwell() 返回空，延时要由上位机 sleep（caps.dwell = "host"）
    - **IO 随运动排队**（实测 2026-11-16）：M121 会自然排在之前的运动之后执行，
      不需要 M400。之前保守设 False 插了 19% 的冗余 M400，已改 True。
    - 无圆弧、行≤128B、单条运动≤60s
    - 每条指令板内固定开销约 200-360ms（这是真正的性能瓶颈，不是网络）
    """

    name = "lc"
    queued_io = True  # 实测：IO 排队，无需 M400
    max_line_len = 128
    from .model import DIALECTS as _D
    caps = _D["lc"]

    def header(self, ctx: Ctx) -> list[str]:
        m = ctx.machine
        out = [
            f"; generated by {APP_NAME} {VERSION}",
            f"; machine={m.name} travel={_f(m.travel_x)}x{_f(m.travel_y)}x{_f(m.travel_z)}",
            "G21",  # mm
            "G90",  # 绝对
            f"M204 A{int(m.accel)} D{int(m.accel)}",
            f"M203 V{int(m.feed_rapid)}",
        ]
        if m.has_home_switch:
            out.append("G28")
        return out

    def ensure_closed(self, ctx: Ctx, io: int, level: int) -> list[str]:
        return [f"M121 U{io} V{level}"]

    def travel(self, ctx: Ctx, x: float, y: float, feed: float) -> list[str]:
        return [f"G0 X{_f(x)} Y{_f(y)} F{int(feed)}"]

    def print_move(self, ctx: Ctx, x: float, y: float, feed: float) -> list[str]:
        return [f"G1 X{_f(x)} Y{_f(y)} F{int(feed)}"]

    def move_z(self, ctx: Ctx, z: float, feed: float) -> list[str]:
        return [f"G0 Z{_f(z)} F{int(feed)}"]

    def valve(self, ctx: Ctx, ev: IOEvent) -> list[str]:
        lines = []
        if not self.queued_io:
            lines.append("M400")  # 等运动停稳，否则 M121 会在解析时刻生效
        lines.append(f"M121 U{ev.io} V{ev.level}")
        return lines

    def dwell(self, ctx: Ctx, ms: int) -> list[str]:
        if ms <= 0:
            return []
        return [f"G4 P{ms}"]

    def wait_motion(self, ctx: Ctx) -> list[str]:
        return ["M400"]

    def footer(self, ctx: Ctx) -> list[str]:
        return ["M400", "; end"]


# ══════════════════════════════════════════════════════════
# LCSystem H5（以太网 UDP，当前主力板）
# ══════════════════════════════════════════════════════════


class H5Dialect:
    """LCSystem H5 以太网板。

    与 R7 网口板的关键差异（均为 2026-11-21 实机验证）：

    - **`G4` 可用**，但 `P` 参数单位是**秒不是毫秒**：
      120ms 要写 `G4 P0.12`。协议文档写的「毫秒」是错的。
      所以 caps.dwell = "gcode"，延时直接写进指令，
      下发器不需要再 sleep，G-code 文件也自带时序。
    - **纯 M 行回 `B` 码**，G 行回 `E` 码（caps.reply_letters = ["E","B"]）
    - **IO 输出只有 4 路**（U0~U3），U4~U7 无效 → caps.io_channels = 4
    - 四轴 X/Y/Z/E，有 G92，有快查询通道
    - IO 随运动排队，不需要 M400
    """

    name = "h5"
    queued_io = True
    max_line_len = 128
    from .model import DIALECTS as _D
    caps = _D["h5"]

    def header(self, ctx: Ctx) -> list[str]:
        m = ctx.machine
        out = [
            f"; generated by {APP_NAME} {VERSION}",
            f"; profile=h5 machine={m.name}",
            f"; travel={_f(m.travel_x)}x{_f(m.travel_y)}x{_f(m.travel_z)}",
            "G21",  # mm
            "G90",  # 绝对
            # H5 支持 M204 设加减速、M203 设 G0 速度
            f"M204 A{int(m.accel)} D{int(m.accel)}",
            f"M203 V{int(m.feed_rapid)}",
        ]
        if m.has_home_switch:
            out.append("G28")
        return out

    def ensure_closed(self, ctx: Ctx, io: int, level: int) -> list[str]:
        self._check_io(io)
        return [f"M121 U{io} V{level}"]

    def travel(self, ctx: Ctx, x: float, y: float, feed: float) -> list[str]:
        return [f"G0 X{_f(x)} Y{_f(y)} F{int(feed)}"]

    def print_move(self, ctx: Ctx, x: float, y: float, feed: float) -> list[str]:
        return [f"G1 X{_f(x)} Y{_f(y)} F{int(feed)}"]

    def move_z(self, ctx: Ctx, z: float, feed: float) -> list[str]:
        return [f"G0 Z{_f(z)} F{int(feed)}"]

    def valve(self, ctx: Ctx, ev: IOEvent) -> list[str]:
        self._check_io(ev.io)
        # M121 在 H5 上走快查询通道（不进队列），但仍排在运动之后生效，
        # 所以不需要 M400。
        return [f"M121 U{ev.io} V{ev.level}"]

    def dwell(self, ctx: Ctx, ms: int) -> list[str]:
        """H5 的 G4 用**秒**作单位，小数可用。

        实测精度（扣除约 76ms 通信基准）：
            P0.12 → 137ms、P0.08 → 86ms、P0.2 → 189ms
        所以直接用 ms/1000 即可，不需要额外补偿。
        """
        if ms <= 0:
            return []
        return [f"G4 P{_fmt_seconds(ms)}"]

    def wait_motion(self, ctx: Ctx) -> list[str]:
        return ["M400"]

    def footer(self, ctx: Ctx) -> list[str]:
        return ["M400", "; end"]

    def _check_io(self, io: int) -> None:
        n = self.caps.io_channels
        if not (0 <= io < n):
            raise ValueError(
                f"H5 板只有 {n} 路 IO 输出（U0~U{n-1}），"
                f"通道号 {io} 越界。改路径的通道号，或换用支持更多路的板子。"
            )


def _fmt_seconds(ms: int) -> str:
    """把毫秒转成秒的字符串，去掉多余的 0：120→"0.12"、1000→"1"、80→"0.08"。"""
    v = ms / 1000.0
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return s or "0"


# ══════════════════════════════════════════════════════════
# Marlin / Ultimaker
# ══════════════════════════════════════════════════════════


class MarlinDialect:
    """Marlin。

    关键：M42 由 G-code 解析器执行，不进规划器队列
    （见 Marlin issue #26803，closed as not planned）。
    所以每个 M42 前必须 M400。
    """

    name = "marlin"
    queued_io = False
    max_line_len = 96
    from .model import DIALECTS as _D
    caps = _D["marlin"]

    def __init__(self, pin_main: int = 11, pin_purge: int | None = None):
        self.pin_main = pin_main
        self.pin_purge = pin_purge

    def _pin(self, io: int) -> int:
        if io == 0:
            return self.pin_main
        if io == 1 and self.pin_purge is not None:
            return self.pin_purge
        return self.pin_main + io

    def header(self, ctx: Ctx) -> list[str]:
        m = ctx.machine
        return [
            f"; generated by {APP_NAME} {VERSION}",
            f"; dialect=marlin pin_main={self.pin_main}",
            "G21",
            "G90",
            f"M204 A{int(m.accel)} D{int(m.accel)}",
            "M302 S0 ; allow cold extrusion",
        ]

    def ensure_closed(self, ctx: Ctx, io: int, level: int) -> list[str]:
        return [f"M42 P{self._pin(io)} S{level}"]

    def travel(self, ctx: Ctx, x: float, y: float, feed: float) -> list[str]:
        return [f"G0 X{_f(x)} Y{_f(y)} F{int(feed)}"]

    def print_move(self, ctx: Ctx, x: float, y: float, feed: float) -> list[str]:
        return [f"G1 X{_f(x)} Y{_f(y)} F{int(feed)}"]

    def move_z(self, ctx: Ctx, z: float, feed: float) -> list[str]:
        return [f"G0 Z{_f(z)} F{int(feed)}"]

    def valve(self, ctx: Ctx, ev: IOEvent) -> list[str]:
        return ["M400", f"M42 P{self._pin(ev.io)} S{ev.level}"]

    def dwell(self, ctx: Ctx, ms: int) -> list[str]:
        if ms <= 0:
            return []
        return [f"G4 P{ms}"]

    def wait_motion(self, ctx: Ctx) -> list[str]:
        return ["M400"]

    def footer(self, ctx: Ctx) -> list[str]:
        return ["M400", "; end"]


