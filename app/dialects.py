class KlipperDialect:
    """Klipper。

    SET_PIN 走 GCodeRequestQueue + register_lookahead_callback，
    写入被调度到运动队列内部的某个打印时刻，不是立即执行。
    → 不需要 M400，可以在移动中开阀。
    """

    name = "klipper"
    queued_io = True
    max_line_len = 0
    from .model import DIALECTS as _D
    caps = _D["klipper"]

    def __init__(self, pins: dict[int, str] | None = None):
        self.pins = pins or {0: "valve_main", 1: "valve_purge"}

    def _pin(self, io: int) -> str:
        return self.pins.get(io, f"valve_{io}")

    def header(self, ctx: Ctx) -> list[str]:
        m = ctx.machine
        return [
            f"; generated by {APP_NAME} {VERSION}",
            "; dialect=klipper",
            "G21",
            "G90",
            f"SET_VELOCITY_LIMIT ACCEL={int(m.accel)}",
        ]

    def ensure_closed(self, ctx: Ctx, io: int, level: int) -> list[str]:
        return [f"SET_PIN PIN={self._pin(io)} VALUE={level}"]

    def travel(self, ctx: Ctx, x: float, y: float, feed: float) -> list[str]:
        return [f"G0 X{_f(x)} Y{_f(y)} F{int(feed)}"]

    def print_move(self, ctx: Ctx, x: float, y: float, feed: float) -> list[str]:
        return [f"G1 X{_f(x)} Y{_f(y)} F{int(feed)}"]

    def move_z(self, ctx: Ctx, z: float, feed: float) -> list[str]:
        return [f"G0 Z{_f(z)} F{int(feed)}"]

    def valve(self, ctx: Ctx, ev: IOEvent) -> list[str]:
        # 不插 M400 —— SET_PIN 自己会排队
        return [f"SET_PIN PIN={self._pin(ev.io)} VALUE={ev.level}"]

    def dwell(self, ctx: Ctx, ms: int) -> list[str]:
        if ms <= 0:
            return []
        return [f"G4 P{ms}"]

    def wait_motion(self, ctx: Ctx) -> list[str]:
        return []  # 不需要

    def footer(self, ctx: Ctx) -> list[str]:
        return ["; end"]


def make_dialect(name: str, **kw) -> Dialect:
    if name == "lc":
        return LCDialect()
    if name == "h5":
        return H5Dialect()
    if name == "marlin":
        return MarlinDialect(pin_main=kw.get("pin_main", 11), pin_purge=kw.get("pin_purge"))
    if name == "klipper":
        return KlipperDialect(pins=kw.get("pins"))
    if name == "f1":
        return F1Dialect()
    raise ValueError(f"unknown dialect: {name}")


