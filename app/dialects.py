"""方言抽象 + 三套实现。

核心是 caps.queued_io：
  True  → IO 随运动排队（Klipper），直接输出，时序精确
  False → IO 由解析器执行（Marlin/待测自研板），必须插 M400 强制停车

这一个字段把「多套方案」压缩成配置。
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol

from .model import IOEvent, Machine, Process


@dataclass
class Ctx:
    """输出一行时的上下文。"""

    machine: Machine
    process: Process
    z: float = 0.0


class Dialect(Protocol):
    name: str
    queued_io: bool
    max_line_len: int

    def header(self, ctx: Ctx) -> list[str]: ...
    def ensure_closed(self, ctx: Ctx, io: int, level: int) -> list[str]: ...
    def travel(self, ctx: Ctx, x: float, y: float, feed: float) -> list[str]: ...
    def move_z(self, ctx: Ctx, z: float, feed: float) -> list[str]: ...
    def valve(self, ctx: Ctx, ev: IOEvent) -> list[str]: ...
    def dwell(self, ctx: Ctx, ms: int) -> list[str]: ...
    def wait_motion(self, ctx: Ctx) -> list[str]: ...
    def footer(self, ctx: Ctx) -> list[str]: ...
    def print_move(self, ctx: Ctx, x: float, y: float, feed: float) -> list[str]: ...


def _f(v: float, nd: int = 3) -> str:
    s = f"{v:.{nd}f}"
    return s.rstrip("0").rstrip(".") if "." in s else s


# ══════════════════════════════════════════════════════════
# LCSystem（自研板，UDP）
# ══════════════════════════════════════════════════════════


class LCDialect:
    """自研 i.MX RT1170 板。

    - 阀：M121 U<n> V0/1
    - IO 是否排队未知（待测），保守按「不排队」处理 → 插 M400
    - 无圆弧、行≤128B、单条运动≤60s
    """

    name = "lc"
    queued_io = False  # 待测；先保守
    max_line_len = 128

    def header(self, ctx: Ctx) -> list[str]:
        m = ctx.machine
        out = [
            "; generated by pathCAM",
            f"; machine={m.name} travel={_f(m.travel_x)}x{_f(m.travel_y)}x{_f(m.travel_z)}",
            "G21",  # mm
            "G90",  # 绝对
            f"M204 A{int(m.accel)} D{int(m.accel)}",
            f"M203 V{int(m.feed_rapid)}",
        ]
        if m.has_home_switch:
            out.append("G28")
        return out

    def ensure_closed(self, ctx: Ctx, io: int, level: int) -> list[str]:
        return [f"M121 U{io} V{level}"]

    def travel(self, ctx: Ctx, x: float, y: float, feed: float) -> list[str]:
        return [f"G0 X{_f(x)} Y{_f(y)} F{int(feed)}"]

    def print_move(self, ctx: Ctx, x: float, y: float, feed: float) -> list[str]:
        return [f"G1 X{_f(x)} Y{_f(y)} F{int(feed)}"]

    def move_z(self, ctx: Ctx, z: float, feed: float) -> list[str]:
        return [f"G0 Z{_f(z)} F{int(feed)}"]

    def valve(self, ctx: Ctx, ev: IOEvent) -> list[str]:
        lines = []
        if not self.queued_io:
            lines.append("M400")  # 等运动停稳，否则 M121 会在解析时刻生效
        lines.append(f"M121 U{ev.io} V{ev.level}")
        return lines

    def dwell(self, ctx: Ctx, ms: int) -> list[str]:
        if ms <= 0:
            return []
        return [f"G4 P{ms}"]

    def wait_motion(self, ctx: Ctx) -> list[str]:
        return ["M400"]

    def footer(self, ctx: Ctx) -> list[str]:
        return ["M400", "; end"]


# ══════════════════════════════════════════════════════════
# Marlin / Ultimaker
# ══════════════════════════════════════════════════════════


class MarlinDialect:
    """Marlin。

    关键：M42 由 G-code 解析器执行，不进规划器队列
    （见 Marlin issue #26803，closed as not planned）。
    所以每个 M42 前必须 M400。
    """

    name = "marlin"
    queued_io = False
    max_line_len = 96

    def __init__(self, pin_main: int = 11, pin_purge: int | None = None):
        self.pin_main = pin_main
        self.pin_purge = pin_purge

    def _pin(self, io: int) -> int:
        if io == 0:
            return self.pin_main
        if io == 1 and self.pin_purge is not None:
            return self.pin_purge
        return self.pin_main + io

    def header(self, ctx: Ctx) -> list[str]:
        m = ctx.machine
        return [
            "; generated by pathCAM",
            f"; dialect=marlin pin_main={self.pin_main}",
            "G21",
            "G90",
            f"M204 A{int(m.accel)} D{int(m.accel)}",
            "M302 S0 ; allow cold extrusion",
        ]

    def ensure_closed(self, ctx: Ctx, io: int, level: int) -> list[str]:
        return [f"M42 P{self._pin(io)} S{level}"]

    def travel(self, ctx: Ctx, x: float, y: float, feed: float) -> list[str]:
        return [f"G0 X{_f(x)} Y{_f(y)} F{int(feed)}"]

    def print_move(self, ctx: Ctx, x: float, y: float, feed: float) -> list[str]:
        return [f"G1 X{_f(x)} Y{_f(y)} F{int(feed)}"]

    def move_z(self, ctx: Ctx, z: float, feed: float) -> list[str]:
        return [f"G0 Z{_f(z)} F{int(feed)}"]

    def valve(self, ctx: Ctx, ev: IOEvent) -> list[str]:
        return ["M400", f"M42 P{self._pin(ev.io)} S{ev.level}"]

    def dwell(self, ctx: Ctx, ms: int) -> list[str]:
        if ms <= 0:
            return []
        return [f"G4 P{ms}"]

    def wait_motion(self, ctx: Ctx) -> list[str]:
        return ["M400"]

    def footer(self, ctx: Ctx) -> list[str]:
        return ["M400", "; end"]


